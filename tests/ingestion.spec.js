async function harness(bytes = sample) {
  const dir = path.join(ROOT, 'tests/.tmp/ingestion', randomUUID());
  await fs.mkdir(dir, { recursive: true });
  const registryFile = path.join(dir, 'registry.json');
  await fs.writeFile(registryFile, json({ version: 1, sources: [source()] }));
  const transport = { bytes, calls: 0 };
  const options = { root: ROOT, registryFile, cache: path.join(dir, 'cache'), database: path.join(dir, 'database'), reports: path.join(dir, 'reports'),
    retryDelayMs: 0, now: () => '2026-09-30T00:00:00.000Z',
    fetchImpl: async () => { transport.calls++; return new Response(transport.bytes, { headers: { 'content-length': String(transport.bytes.length), etag: 'fixture' } }); } };
  const engine = await new IngestionEngine(options).setup('all');
  const batch = await engine.download();
  return { dir, engine, transport, options, batch };
}

test('cached sources replay deterministically and generated bytes remain identical', async () => {
  const h = await harness();
  const plan = await h.engine.validate({ batch: h.batch });
  const first = await h.engine.commit(plan);
  const before = await fs.readFile(path.join(h.options.database, 'current.json'));
  const offline = await new IngestionEngine({ ...h.options, fetchImpl: () => { throw new Error('Network used during offline replay'); } }).setup('all');
  const replay = await offline.validate();
  const second = await offline.commit(replay);
  expect(second.generation).toBe(first.generation);
  expect(second.changed).toBe(false);
  expect(replay.changes.additions).toEqual([]);
  expect(replay.changes.changes).toEqual([]);
  expect(replay.records).toEqual(plan.records);
  expect(await fs.readFile(path.join(h.options.database, 'current.json'))).toEqual(before);
});

